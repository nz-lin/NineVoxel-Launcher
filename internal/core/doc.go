// Package core 提供启动器「共享游戏核心」的管理能力。
//
// 核心 = 所有实例共用、安装后不再变化、由启动器管理的游戏运行资源：
// libraries、assets、versions（含 natives）。它位于 artifact.DataRoot()，
// 不额外引入物理 core/ 目录层级。
//
// # 设计目标
//
//   - **一份存储**：同一份游戏资源在磁盘上只存在一份。实例目录不再保存
//     libraries / assets / versions，只保存可变状态（mods、saves、config、logs）。
//   - **安装即缓存**：下载产物直接落在最终布局（libraries/<maven>、
//     assets/objects/<hash>），不再经过第二层内容寻址缓存。
//   - **幂等安装**：同一安装配方只执行一次官方 Installer，后续实例复用产物。
//   - **可校验**：每次成功安装产出安装清单，记录全部必需文件的大小与 SHA-256，
//     用于发现手动删除、损坏等异常。
//   - **可修复、可重建**：核心损坏时有明确的恢复路径，而不是让用户逐个重装实例。
//
// # 硬约束
//
//   - 核心目录的**写入**只能经由本包的导出方法。instance / launch / loader
//     可以读取核心，但不得自行删除、覆盖或修复核心文件。
//   - 所有写操作必须先取 Global 读锁再取更细粒度的锁，顺序固定为
//     Global → Identity → Version → Artifact。反向获取视为 bug。
//   - 运行中的游戏持有该版本的租约（Lease）；租约未释放时不得删除或替换
//     对应版本目录，也不得重建核心。
//   - 安装清单是唯一判据：清单缺失或校验失败即视为未完整安装。
//     不使用「标记文件存在即完整」这种弱判据。
//   - 文件替换一律走「暂存 → 校验 → 原子改名」，不在原地修改已存在的文件。
//
// # 与同级包的关系
//
//   - loader 负责加载器元数据查询与官方 Installer 的下载和执行；
//     本包只在安装事务内调用它，不允许其他包直接调用 Installer 改核心。
//   - instance 负责实例配置与可变数据；它引用本包解析出的版本 ID。
//   - launch 负责双根启动计划；本包只提供路径与版本信息。
//
// # 非目标
//
//   - 不实现自己的加载器安装器：加载器产物一律由官方 Installer 生成，
//     本包只负责验证与生命周期管理。
//   - 不维护加载器元数据服务：不缓存「加载器 × 版本 × MC 版本」的成品描述。
//   - 不提供文件级垃圾回收：本期只做版本级回收，未引用的 libraries / assets
//     暂时保留，由后续版本处理。
//   - 不支持多进程共享同一数据根：锁只在进程内生效。
//   - 不支持 Windows 与 macOS 共用同一数据根：natives 与安装配方均与平台相关。
package core
